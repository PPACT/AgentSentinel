#!/usr/bin/env node
// Tauri CLI 包装：
// 1) CARGO_TARGET_DIR → <项目根>/.claude/tauri-target（避开项目树 Low 完整性标签的影响）；
// 2) VITE_AGENT_SENTINEL_ROOT → 项目根；
// 3) 生成本机能力文件 capabilities/local.dev.json，允许读取项目 daemon 的 token/daemon.json
//    （绝对路径因机器而异，故生成为 gitignored 文件，不写入仓库）。
import { spawn } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const experimentDir = path.resolve(scriptDir, "..");
const projectRoot = path.resolve(experimentDir, "..", "..");
const targetDir = path.join(projectRoot, ".claude", "tauri-target");
const capabilitiesDir = path.join(experimentDir, "src-tauri", "capabilities");
const localCapability = path.join(capabilitiesDir, "local.dev.json");

mkdirSync(targetDir, { recursive: true });
mkdirSync(capabilitiesDir, { recursive: true });

const rootPosix = projectRoot.replaceAll("\\", "/");
const appDataBase = process.env.APPDATA ?? path.join(projectRoot, ".claude");
const agentDataDir =
  process.env.SENTINEL_DATA_DIR ?? path.join(appDataBase, "AgentSentinel");
const agentDataPosix = agentDataDir.replaceAll("\\", "/");
const capability = `${JSON.stringify(
  {
    $schema: "../gen/schemas/desktop-schema.json",
    identifier: "local-dev",
    description: "Local dev paths generated by scripts/tauri.mjs (gitignored)",
    windows: ["main"],
    permissions: [
      {
        identifier: "fs:allow-read-text-file",
        allow: [
          { path: `${rootPosix}/.claude/orchestrator/token` },
          { path: `${rootPosix}/.claude/orchestrator/daemon.json` },
          { path: `${rootPosix}/.claude/workspaces/*/token` },
          { path: `${rootPosix}/.claude/workspaces/*/daemon.json` },
          { path: `${agentDataPosix}/workspaces/*/token` },
          { path: `${agentDataPosix}/workspaces/*/daemon.json` },
        ],
      },
    ],
  },
  null,
  2,
)}\n`;

// tauri-build watches capability files; rewriting identical content只改 mtime，
// 会让每次启动都触发整包 Rust 重编译（约 30-40s）。仅在内容变化时落盘。
let currentCapability = "";
try {
  currentCapability = readFileSync(localCapability, "utf8");
} catch {
  currentCapability = "";
}
if (currentCapability !== capability) {
  writeFileSync(localCapability, capability, "utf8");
}

const child = spawn("tauri", process.argv.slice(2), {
  stdio: "inherit",
  shell: true,
  windowsHide: true,
  env: {
    ...process.env,
    CARGO_TARGET_DIR: targetDir,
    VITE_AGENT_SENTINEL_ROOT: process.env.VITE_AGENT_SENTINEL_ROOT ?? projectRoot,
  },
});

child.on("exit", (code, signal) => {
  if (signal) process.kill(process.pid, signal);
  process.exit(code ?? 1);
});
